// 原型快照从应用唯一词条和品牌源生成，避免设计预览另维护一份翻译。
import { createRequire } from 'node:module';
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const data = createRequire(import.meta.url)(fileURLToPath(new URL('frontend/i18n-data.js', root)));
const nav = ['语言', '权限', '模型与存储', 'AI 功能', '手机连接'];
const snapshot = {
  onboardingMotionCopy: data.onboardingMotionCopy,
  appCopy: { stageLabels: {} },
  catalog: Object.fromEntries(
    Object.keys(data.onboardingMotionCopy).map((locale) => [
      locale,
      {
        labels: Object.fromEntries(
          nav.map((key) => [
            key,
            data.appCopy.stageLabels[key]?.[locale] || data.catalog[locale].labels[key] || key,
          ]),
        ),
      },
    ]),
  ),
};
const assets = new URL('docs/redesign-2026-10-12/videos/onboarding-motion/assets/', root);
await writeFile(
  new URL('onboarding-copy.js', assets),
  '// Generated by scripts/sync-onboarding-preview.mjs; do not edit.\nwindow.BreviaLocaleData = ' +
    JSON.stringify(snapshot, null, 2) +
    ';\n',
);
await copyFile(
  new URL('frontend/assets/brevia-mark.svg', root),
  new URL('brevia-mark.svg', assets),
);
console.log('Onboarding preview copy and logo synced from application sources.');

// 前三步原型与应用共用组件快照；预览不另维护一条动画时间轴。
for (const name of ['onboarding-motion.js', 'onboarding-motion.css'])
  await copyFile(new URL('frontend/' + name, root), new URL(name, assets));
const components = await readFile(new URL('frontend/ui-components.js', root), 'utf8');
const end = components.indexOf('/** 设置导航');
if (end < 0) throw new Error('Onboarding component boundary not found');
await writeFile(
  new URL('onboarding-components.js', assets),
  '// Generated by scripts/sync-onboarding-preview.mjs; do not edit.\n' + components.slice(0, end),
);
